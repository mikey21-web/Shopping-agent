function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a += 0x6d2b79f5;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function detectLanguageFor(body: string): SeedReview['language'] {
  const devanagari = (body.match(/[\u0900-\u097F]/g) ?? []).length;
  if (devanagari / Math.max(1, body.length) > 0.12) return 'hi';
  const markers = ['hai', 'nahi', 'bahut', 'accha', 'acha', 'mast', 'paisa', 'bijli', 'dhulai'];
  const words = body.toLowerCase().split(/\s+/);
  const hits = words.filter((word) => markers.includes(word)).length;
  if (hits / Math.max(1, words.length) > 0.05) return 'hinglish';
  return 'en';
}

/** Build the non-electronics review corpus deterministically. */
export function buildNonElectronicsReviews(): SeedReview[] {
  const random = mulberry32(77020261);
  const reviews: SeedReview[] = [];
  let counter = 0;

  for (const plan of REVIEW_PLANS) {
    for (let i = 0; i < plan.count; i += 1) {
      counter += 1;
      const template = plan.pool[Math.floor(random() * plan.pool.length)];
      if (!template) continue;
      const daysAgo = Math.min(600, Math.max(2, Math.round(600 * (1 - i / plan.count))));
      reviews.push({
        listingId: plan.listingId,
        rating: template.rating,
        body: template.body,
        title: template.title,
        author: AUTHORS[Math.floor(random() * AUTHORS.length)],
        verifiedPurchase: random() > 0.15,
        daysAgo,
        language: detectLanguageFor(template.body),
        helpfulVotes: Math.floor(random() * 40),
      });
    }
  }

  return reviews;
}
